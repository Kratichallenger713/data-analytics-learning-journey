a = [1, 2, 3]

# Membership operators in Python are used to check whether a value exists in a sequence or collection, such as a string, list, tuple, set, or dictionary.
print(1 in a) # Membership Operator
print(1 not in a) # Membership Operator

# Output of 1 in a is True because 1 is present in a
# Output of 1 not in a is rAlse because 1 is present in a

