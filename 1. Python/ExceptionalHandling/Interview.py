# Interview Questions
# Q1. try block ka use kyon hota hai?

# Answer: Risky code ko likhne ke liye jahan runtime error aane ki possibility hoti hai.

# Q2. except kab execute hota hai?

# Answer: Jab try block mein exception aata hai.

# Q3. else kab execute hota hai?

# Answer: Jab try block mein koi exception nahi aata.

# Q4. finally kab execute hota hai?

# Answer: Hamesha execute hota hai, chahe exception aaye ya na aaye.

# Q5. raise keyword ka use kya hai?

# Answer: Khud se exception generate karne ke liye raise keyword ka use hota hai.


# try → Risky code likho.
# except → Error handle karo.
# else → Error na aaye to execute hoga.
# finally → Hamesha execute hoga.
# raise → Khud se exception generate karo.